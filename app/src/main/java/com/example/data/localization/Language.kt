    fun get(key: String, language: AppLanguage): String {
        val map = if (language == AppLanguage.URDU) ur else en
        val result = map[key] ?: en[key]
        if (result != null) return result

        // Defensive fallback: Never display raw snake_case like "laundry_wash_and_iron"
        return formatFallbackKey(key)
    }

    private fun formatFallbackKey(key: String): String {
        return key.removePrefix("cat_")
            .removePrefix("step_")
            .removePrefix("laundry_")
            .replace('_', ' ')
            .trim()
            .split(" ")
            .filter { it.isNotBlank() }
            .joinToString(" ") { word ->
                word.lowercase().replaceFirstChar { if (it.isLowerCase()) it.titlecase() else it.toString() }
            }
    }
